"""The root-owned ``engine-launch`` script that sudo runs as each user.

sudoers lets the ``mira-server`` account run exactly this file as members of
``mira-users``, and ``engine-launch stop`` as any other non-root account, so it
can still stop the engine of someone removed from the group::

    mira-server ALL=(%mira-users) NOPASSWD: /usr/local/libexec/mira/engine-launch
    mira-server ALL=(ALL,!root) NOPASSWD: /usr/local/libexec/mira/engine-launch stop

The script accepts one argument, ``start``, ``status`` or ``stop``, and reads no
other input. It discards the caller's environment, builds a minimal one from the
passwd entry of the uid it runs as (``HOME``, ``MIRA_HOME=~/.mira``, ``PATH``)
and execs the system engine::

    <engine python> -I -m mira_engine remote attach --json   # start
    <engine python> -I -m mira_engine remote status --json   # status
    <engine python> -I -m mira_engine remote stop --json     # stop
"""

from __future__ import annotations

import os
import stat
import sys
import tempfile
from pathlib import Path

from mira_server.spawner.base import ACTION_ARGS

MARKER = "# mira-server-engine-launcher: 1"
DEFAULT_RELATIVE_PATH = Path("libexec") / "mira" / "engine-launch"

_TEMPLATE = '''#!{python} -I
# Mira Server engine launcher. Generated by `mira-server install-launcher`; do not edit.
{marker}
#
# sudo runs this as a member of the Mira users group. It accepts only
# start|status|stop, ignores the caller's environment and execs the system
# engine's `mira remote` command for the account it runs as.
import os
import pwd
import stat
import sys

ENGINE_PYTHON = {python!r}
ACTIONS = {actions!r}


def main():
    if len(sys.argv) != 2 or sys.argv[1] not in ACTIONS:
        sys.stderr.write("usage: engine-launch start|status|stop\\n")
        return 64
    uid = os.geteuid()
    if uid == 0 or os.getuid() != uid:
        sys.stderr.write("engine-launch: refusing to run as root or with mixed uids\\n")
        return 77
    entry = pwd.getpwuid(uid)
    home = entry.pw_dir
    engine_bin = os.path.dirname(ENGINE_PYTHON)
    env = {{
        "HOME": home,
        "USER": entry.pw_name,
        "LOGNAME": entry.pw_name,
        "SHELL": entry.pw_shell or "/bin/sh",
        "MIRA_HOME": os.path.join(home, ".mira"),
        "PATH": engine_bin + ":/usr/local/bin:/usr/bin:/bin",
        "LANG": "C.UTF-8",
        "PYTHONUNBUFFERED": "1",
    }}
    runtime = "/run/user/%d" % uid
    try:
        info = os.stat(runtime)
        if stat.S_ISDIR(info.st_mode) and info.st_uid == uid and not info.st_mode & 0o077:
            # The same runtime dir a login (Remote-SSH) engine uses, so both see one lock.
            env["XDG_RUNTIME_DIR"] = runtime
    except OSError:
        pass
    try:
        os.chdir(home)
    except OSError:
        os.chdir("/")
    argv = [ENGINE_PYTHON, "-I", "-m", "mira_engine", "remote"] + list(ACTIONS[sys.argv[1]])
    os.execve(ENGINE_PYTHON, argv, env)


if __name__ == "__main__":
    sys.exit(main())
'''


class LauncherInstallError(Exception):
    pass


def render_launcher(engine_python: str) -> str:
    if not os.path.isabs(engine_python):
        raise LauncherInstallError(f"--engine-python must be an absolute path, got {engine_python!r}")
    if any(ch.isspace() for ch in engine_python) or len(engine_python) > 200:
        raise LauncherInstallError("the engine interpreter path must not contain whitespace (shebang line)")
    actions = {action: list(args) for action, args in ACTION_ARGS.items()}
    return _TEMPLATE.format(python=engine_python, marker=MARKER, actions=actions)


def default_launcher_path(prefix: Path | str) -> Path:
    return Path(prefix) / DEFAULT_RELATIVE_PATH


def install_launcher(path: Path, engine_python: str, *, require_root: bool = True) -> Path:
    """Write the launcher atomically, mode 0755, owned by root when run as root."""
    content = render_launcher(engine_python)
    if require_root and os.geteuid() != 0:
        raise LauncherInstallError("install-launcher must run as root so the launcher is root-owned "
                                   "(use --no-root-check only for testing)")
    path.parent.mkdir(mode=0o755, parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".engine-launch.", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(content)
            handle.flush()
            os.fchmod(handle.fileno(), 0o755)
            if os.geteuid() == 0:
                os.fchown(handle.fileno(), 0, 0)
            os.fsync(handle.fileno())
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise
    return path


def sudoers_line(path: Path, *, server_user: str, users_group: str) -> str:
    return f"{server_user} ALL=(%{users_group}) NOPASSWD: {path}"


def sudoers_stop_line(path: Path, *, server_user: str) -> str:
    """Lets Mira Server stop the engine of someone no longer in the users group.

    sudoers matches the argument exactly, so only ``stop`` is allowed; the
    launcher itself also refuses to run as root.
    """
    return f"{server_user} ALL=(ALL,!root) NOPASSWD: {path} stop"


def sudoers_rules(path: Path, *, server_user: str, users_group: str) -> list[str]:
    return [sudoers_line(path, server_user=server_user, users_group=users_group),
            sudoers_stop_line(path, server_user=server_user)]


def granted_launcher_rules(sudo_list: str, path: Path) -> tuple[bool, bool]:
    """Read ``sudo -n -l`` output: (launcher allowed, ``stop`` allowed as any account).

    Only NOPASSWD entries count: Mira Server runs ``sudo -n`` and cannot answer
    a password prompt. The second value needs a rule whose run-as list starts
    with ``ALL`` (such as ``(ALL, !root)``), not just the users group.
    """
    launcher, stop = str(path), f"{path} stop"
    full = stop_for_others = False
    for line in sudo_list.splitlines():
        if "NOPASSWD:" not in line:
            continue
        spec, commands = line.split("NOPASSWD:", 1)
        names = {" ".join(command.split()) for command in commands.split(",")}
        runas = spec[spec.find("(") + 1:spec.find(")")] if "(" in spec and ")" in spec else ""
        any_user = runas.split(":", 1)[0].split(",")[0].strip() == "ALL"
        if launcher in names:
            full = True
        if any_user and (launcher in names or stop in names):
            stop_for_others = True
    return full, stop_for_others


def read_engine_python(path: Path) -> str | None:
    try:
        text = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return None
    for line in text.splitlines():
        if line.startswith("ENGINE_PYTHON = "):
            value = line.split("=", 1)[1].strip()
            if len(value) >= 2 and value[0] == value[-1] and value[0] in "'\"":
                return value[1:-1]
    return None


def _unsafe_owner_or_mode(path: Path, info: os.stat_result) -> str | None:
    if info.st_uid != 0:
        return f"{path} is owned by uid {info.st_uid}, not root"
    if info.st_mode & (stat.S_IWGRP | stat.S_IWOTH):
        return f"{path} is writable by group or others (mode {info.st_mode & 0o777:o})"
    return None


def inspect_launcher(path: Path) -> list[str]:
    """Problems that would let someone other than root change what sudo runs."""
    problems: list[str] = []
    try:
        info = path.lstat()
    except FileNotFoundError:
        return [f"{path} does not exist; run `mira-server install-launcher`"]
    if stat.S_ISLNK(info.st_mode) or not stat.S_ISREG(info.st_mode):
        return [f"{path} must be a regular file, not a symlink or special file"]
    if not info.st_mode & stat.S_IXUSR:
        problems.append(f"{path} is not executable")
    issue = _unsafe_owner_or_mode(path, info)
    if issue:
        problems.append(issue)
    for parent in path.resolve().parents:
        try:
            pinfo = parent.stat()
        except OSError:
            continue
        issue = _unsafe_owner_or_mode(parent, pinfo)
        if issue and not (pinfo.st_mode & stat.S_ISVTX and pinfo.st_uid == 0):
            problems.append(issue)
    try:
        text = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        text = ""
    if MARKER not in text:
        problems.append(f"{path} was not generated by `mira-server install-launcher`")
    python = read_engine_python(path)
    if python is None:
        problems.append(f"{path} names no engine interpreter")
    elif not (os.path.isfile(python) and os.access(python, os.X_OK)):
        problems.append(f"engine interpreter {python} is missing or not executable")
    return problems


def default_engine_python() -> str:
    return sys.executable
